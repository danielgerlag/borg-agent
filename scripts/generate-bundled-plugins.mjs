import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginsDirectory = path.join(projectRoot, "plugins");

const entries = await readdir(pluginsDirectory, { withFileTypes: true });
const plugins = [];

for (const entry of entries) {
  if (!entry.isDirectory()) {
    continue;
  }

  const pluginDirectory = path.join(pluginsDirectory, entry.name);
  const packagePath = path.join(pluginDirectory, "package.json");
  const packageJson = JSON.parse(await readFile(packagePath, "utf8"));
  if (!packageJson.borg) {
    continue;
  }

  const { name, borg } = packageJson;
  if (
    typeof name !== "string" ||
    typeof borg.id !== "string" ||
    typeof borg.manifest !== "string" ||
    typeof borg.main !== "string" ||
    (borg.ui !== undefined && typeof borg.ui !== "string")
  ) {
    throw new Error(`Invalid Borg plugin metadata in ${packagePath}`);
  }

  const manifestPath = path.resolve(pluginDirectory, borg.manifest);
  if (!manifestPath.startsWith(`${pluginDirectory}${path.sep}`)) {
    throw new Error(`Plugin manifest escapes its package directory: ${manifestPath}`);
  }

  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  const main = `${name}${borg.main}`;
  const ui = borg.ui === undefined ? undefined : `${name}${borg.ui}`;
  if (
    manifest.id !== borg.id ||
    manifest.main !== main ||
    manifest.ui !== ui
  ) {
    throw new Error(
      `Borg metadata and static manifest disagree in ${packagePath}`,
    );
  }

  plugins.push({
    id: borg.id,
    manifest,
    main,
    ui,
  });
}

plugins.sort((left, right) => left.id.localeCompare(right.id));
const duplicateIds = plugins.filter(
  (plugin, index) => plugins.findIndex((candidate) => candidate.id === plugin.id) !== index,
);
if (duplicateIds.length > 0) {
  throw new Error(`Duplicate bundled plugin IDs: ${duplicateIds.map(({ id }) => id).join(", ")}`);
}

const mainEntries = plugins
  .map(
    (plugin) => `  {
    manifest: ${JSON.stringify(plugin.manifest, null, 2).replaceAll("\n", "\n    ")},
    loadMain: async () =>
      (require(${JSON.stringify(plugin.main)}) as { default: PluginDefinition }).default,
  },`,
  )
  .join("\n");
const mainSource = `// Generated by scripts/generate-bundled-plugins.mjs. Do not edit.
import type { PluginSource } from "@borg/kernel";
import type { PluginDefinition } from "@borg/plugin-sdk";

export const bundledMainPlugins: readonly PluginSource[] = [
${mainEntries}
];
`;

const uiEntries = plugins
  .filter((plugin) => plugin.ui !== undefined)
  .map(
    (plugin) => `  ${JSON.stringify(plugin.id)}: async () => import(${JSON.stringify(plugin.ui)}),`,
  )
  .join("\n");
const uiSource = `// Generated by scripts/generate-bundled-plugins.mjs. Do not edit.
import type { PluginUiDefinition } from "@borg/plugin-sdk";
import type { Component } from "solid-js";

export type UiPluginLoader = () => Promise<{
  readonly default: PluginUiDefinition<Component>;
}>;

export const bundledUiPlugins: Readonly<Record<string, UiPluginLoader>> = {
${uiEntries}
};
`;

await writeFile(
  path.join(projectRoot, "apps/desktop/src/main/bundled-plugins.ts"),
  mainSource,
  "utf8",
);
await writeFile(
  path.join(projectRoot, "apps/desktop/src/renderer/bundled-ui-plugins.ts"),
  uiSource,
  "utf8",
);
