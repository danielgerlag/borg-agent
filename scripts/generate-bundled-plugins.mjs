import { createRequire } from "node:module";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const desktopPackageJsonPath = path.join(projectRoot, "apps/desktop/package.json");

const requireFromDesktop = createRequire(desktopPackageJsonPath);
let desktopDistribution;
try {
  desktopDistribution = requireFromDesktop("@borg/distribution-desktop").desktopDistribution;
} catch (error) {
  throw new Error(
    "Could not load @borg/distribution-desktop. Build the distribution package before generating bundled plugins.",
    { cause: error },
  );
}
if (!desktopDistribution || !Array.isArray(desktopDistribution.plugins)) {
  throw new Error("@borg/distribution-desktop did not export desktopDistribution.plugins");
}
const declaredIds = desktopDistribution.plugins.map((entry) => {
  if (typeof entry === "string") {
    return entry;
  }
  if (entry && typeof entry.id === "string") {
    return entry.id;
  }
  throw new Error("Desktop distribution has a plugin entry without an id");
});
const declaredIdSet = new Set(declaredIds);

async function discoverPackages(directory) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error && error.code === "ENOENT") {
      return [];
    }
    throw error;
  }

  const found = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }

    const pluginDirectory = path.join(directory, entry.name);
    const packagePath = path.join(pluginDirectory, "package.json");
    const packageJson = JSON.parse(await readFile(packagePath, "utf8"));
    if (!packageJson.borg) {
      continue;
    }

    const { name, borg } = packageJson;
    if (
      typeof name !== "string" ||
      typeof borg.id !== "string" ||
      typeof borg.manifest !== "string" ||
      typeof borg.main !== "string" ||
      (borg.ui !== undefined && typeof borg.ui !== "string")
    ) {
      throw new Error(`Invalid Borg plugin metadata in ${packagePath}`);
    }

    const manifestPath = path.resolve(pluginDirectory, borg.manifest);
    if (!manifestPath.startsWith(`${pluginDirectory}${path.sep}`)) {
      throw new Error(`Plugin manifest escapes its package directory: ${manifestPath}`);
    }

    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    const main = `${name}${borg.main}`;
    const ui = borg.ui === undefined ? undefined : `${name}${borg.ui}`;
    if (
      manifest.id !== borg.id ||
      manifest.main !== main ||
      manifest.ui !== ui
    ) {
      throw new Error(
        `Borg metadata and static manifest disagree in ${packagePath}`,
      );
    }

    found.push({
      id: borg.id,
      name,
      manifest,
      main,
      ui,
    });
  }
  return found;
}

const plugins = [
  ...(await discoverPackages(path.join(projectRoot, "plugins"))),
  ...(await discoverPackages(path.join(projectRoot, "examples"))),
];

plugins.sort((left, right) => left.id.localeCompare(right.id));
const packagesById = new Map();
for (const plugin of plugins) {
  const names = packagesById.get(plugin.id) ?? [];
  names.push(plugin.name);
  packagesById.set(plugin.id, names);
}
const sharedIds = [...packagesById.entries()].filter(([, names]) => names.length > 1);
if (sharedIds.length > 0) {
  throw new Error(
    `Plugin packages share an id: ${sharedIds
      .map(([id, names]) => `${id} (${names.join(", ")})`)
      .join("; ")}`,
  );
}

const missingIds = declaredIds.filter((id) => !packagesById.has(id));
if (missingIds.length > 0) {
  throw new Error(
    `Desktop distribution declares plugin ids with no package: ${missingIds.join(", ")}`,
  );
}

const desktopPackage = JSON.parse(await readFile(desktopPackageJsonPath, "utf8"));
const desktopDependencies = desktopPackage.dependencies ?? {};
const selected = plugins.filter((plugin) => declaredIdSet.has(plugin.id));
const missingDependencies = selected.filter(
  (plugin) => desktopDependencies[plugin.name] === undefined,
);
if (missingDependencies.length > 0) {
  throw new Error(
    `Selected plugins are not dependencies of @borg/desktop: ${missingDependencies
      .map((plugin) => `${plugin.id} (${plugin.name})`)
      .join(", ")}`,
  );
}

const mainEntries = selected
  .map(
    (plugin) => `  {
    manifest: ${JSON.stringify(plugin.manifest, null, 2).replaceAll("\n", "\n    ")},
    loadMain: async () =>
      (require(${JSON.stringify(plugin.main)}) as { default: PluginDefinition }).default,
  },`,
  )
  .join("\n");
const mainSource = `// Generated by scripts/generate-bundled-plugins.mjs. Do not edit.
import type { PluginSource } from "@borg-agent/kernel";
import type { PluginDefinition } from "@borg-agent/plugin-sdk";

export const bundledMainPlugins: readonly PluginSource[] = [
${mainEntries}
];
`;

const uiEntries = selected
  .filter((plugin) => plugin.ui !== undefined)
  .map(
    (plugin) => `  ${JSON.stringify(plugin.id)}: async () => import(${JSON.stringify(plugin.ui)}),`,
  )
  .join("\n");
const uiSource = `// Generated by scripts/generate-bundled-plugins.mjs. Do not edit.
import type { PluginUiDefinition } from "@borg-agent/plugin-sdk";
import type { Component } from "solid-js";

export type UiPluginLoader = () => Promise<{
  readonly default: PluginUiDefinition<Component>;
}>;

export const bundledUiPlugins: Readonly<Record<string, UiPluginLoader>> = {
${uiEntries}
};
`;

await writeFile(
  path.join(projectRoot, "apps/desktop/src/main/bundled-plugins.ts"),
  mainSource,
  "utf8",
);
await writeFile(
  path.join(projectRoot, "apps/desktop/src/renderer/bundled-ui-plugins.ts"),
  uiSource,
  "utf8",
);
